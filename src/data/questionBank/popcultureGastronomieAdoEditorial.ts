import { Question } from '../../types';

/**
 * Cartes ado manquantes en popculture et en gastronomie.
 *
 * Ces deux catégories complétaient leur niveau ado en recopiant des cartes
 * enfant (65 et 27 respectivement). Ces banques les remplacent par des cartes
 * écrites pour le niveau, avec une part assumée de culture francophone et
 * belge, et une explication qui apprend quelque chose à chaque fois.
 */
type TeenCard = [
  question: string,
  /** La bonne réponse figure en premier ; la position est répartie ensuite. */
  options: [string, string, string, string],
  explanation: string,
];

function cards(
  categoryId: 'popculture' | 'gastronomie',
  prefix: string,
  rows: TeenCard[],
): Question[] {
  return rows.map(([question, options, explanation], index) => {
    const rotation = index % 4;
    return {
      id: `${prefix}_${String(index + 1).padStart(3, '0')}`,
      categoryId,
      question,
      options: options.map(
        (_, position) => options[(position + options.length - rotation) % options.length],
      ),
      correctAnswerIndex: rotation,
      difficulty: 'ado',
      explanation,
    };
  });
}

