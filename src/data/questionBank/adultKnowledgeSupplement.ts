import { CategoryId, Question } from '../../types';

/**
 * Complément adulte, entièrement rédigé.
 *
 * Ce fichier générait auparavant ses cartes mécaniquement : 151 questions de
 * tableau périodique (« Quel est le symbole chimique du thulium ? »), 26
 * questions de variétés et 30 questions « De quel pays vient… », toutes dotées
 * d'une explication qui se contentait de répéter la réponse. Ces cartes ne
 * remplissaient ni l'objectif de plaisir ni celui d'apprentissage : les options
 * étaient quatre nombres nus ou quatre noms tirés au sort dans la même liste.
 *
 * Le remplacement conserve exactement les mêmes volumes par catégorie
 * (151 sciences, 31 popculture, 30 gastronomie, 3 sports) mais chaque carte est
 * relue : un fait grand public, des distracteurs crédibles et une explication
 * qui ajoute quelque chose. Une douzaine de cartes de tableau périodique
 * subsistent, sur des éléments que tout le monde a déjà croisés.
 */
type AdultCard = [
  question: string,
  /** La bonne réponse figure en premier ; la position est répartie ensuite. */
  options: [string, string, string, string],
  explanation: string,
];

function cards(categoryId: CategoryId, prefix: string, rows: AdultCard[]): Question[] {
  return rows.map(([question, options, explanation], index) => {
    const rotation = index % 4;
    return {
      id: `${prefix}_${String(index + 1).padStart(3, '0')}`,
      categoryId,
      question,
      options: options.map(
        (_, position) => options[(position + options.length - rotation) % options.length],
      ),
      correctAnswerIndex: rotation,
      difficulty: 'adulte',
      explanation,
    };
  });
}

