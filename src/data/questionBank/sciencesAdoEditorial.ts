/**
 * Niveau ado de la catégorie sciences.
 *
 * Cette banque existe parce que la catégorie n'avait aucune carte ado propre :
 * le niveau était complété en recopiant la banque enfant, ce qui supprimait
 * une marche entière de la progression. Le ton visé est celui du collège et du
 * début du secondaire : un fait situé, une explication qui apprend quelque
 * chose, et des distracteurs crédibles mais départageables par le raisonnement.
 */
type TeenCard = [
  question: string,
  /** La bonne réponse figure en premier ; la position est répartie ensuite. */
  options: [string, string, string, string],
  explanation: string,
];

function cards(prefix: string, rows: TeenCard[]): Question[] {
  return rows.map(([question, options, explanation], index) => {
    const rotation = index % 4;
    return {
      id: `${prefix}_${String(index + 1).padStart(3, '0')}`,
      categoryId: 'sciences',
      question,
      options: options.map(
        (_, position) => options[(position + options.length - rotation) % options.length],
      ),
      correctAnswerIndex: rotation,
      difficulty: 'ado',
      explanation,
    };
  });
}

